export const TEXTS: Record<Language, Texts> = { en, he }

export function errorText(result: ApiResult, t: Texts): string {
  if (result.ok) return ''
  if (result.error === 'too_many_attempts') return t.tooManyAttempts(result.retryAfter)
  return t.errors[result.error] ?? t.unexpected
}
